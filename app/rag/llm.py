import json
import os
import re
from typing import Any

import ollama

MODEL = os.getenv("OLLAMA_MODEL", "llama3.1:8b")
RECENCY_INSTRUCTION = (
    "Reports are listed with their dates. If the same vital, condition, allergy, "
    "or medication appears with different values across multiple reports, use "
    "ONLY the value from the most recently dated report, and disregard older "
    "conflicting values. Still include historical/past conditions in the "
    "'history' category even if outdated, where it's clearly a past event rather "
    "than a current conflicting value."
)
AI_DISCLAIMER = (
    "This summary was generated by AI and is not a substitute for professional "
    "medical advice."
)


def _context_text(context_chunks: list[str]) -> str:
    return "\n\n".join(
        f"Report excerpt {index}:\n{chunk}"
        for index, chunk in enumerate(context_chunks, start=1)
    )


def _response_content(response: Any) -> str:
    if isinstance(response, dict):
        message = response.get("message", {})
        if isinstance(message, dict):
            return str(message.get("content", ""))
        return str(getattr(message, "content", ""))

    message = getattr(response, "message", None)
    return str(getattr(message, "content", ""))


def generate_summary(patient_name: str, context_chunks: list[str]) -> str:
    """Generate a concise, context-grounded summary for a patient."""
    response = ollama.chat(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": (
                    "You summarize medical report excerpts conservatively. "
                    "Use only facts explicitly present in the provided context. "
                    "Do not diagnose, infer, or invent information. Write a "
                    "3-5 sentence narrative summary and end with this exact "
                    "disclaimer: This summary was generated by AI and is not "
                    "a substitute for professional medical advice."
                    f" {RECENCY_INSTRUCTION}"
                ),
            },
            {
                "role": "user",
                "content": (
                    f"Summarize the following report excerpts for "
                    f"{patient_name}. Reports are listed with their dates:\n\n"
                    f"{_context_text(context_chunks)}"
                ),
            },
        ],
    )
    summary = _response_content(response).strip()
    if not summary.endswith(AI_DISCLAIMER):
        summary = f"{summary}\n\n{AI_DISCLAIMER}" if summary else AI_DISCLAIMER
    return summary


def _empty_structured_data() -> dict[str, list]:
    return {
        "allergies": [],
        "conditions": [],
        "medications": [],
        "history": [],
        "vitals": [],
    }


def _strip_markdown_fencing(content: str) -> str:
    stripped = content.strip()
    fenced_match = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", stripped, re.DOTALL)
    return fenced_match.group(1).strip() if fenced_match else stripped


def extract_structured_data(context_chunks: list[str]) -> dict:
    """Extract only explicitly reported clinical data into a fixed JSON shape."""
    prompt = (
        "Read the provided medical report excerpts and extract ONLY information "
        "explicitly present in them. Categorize information as follows: "
        "vitals are any numeric lab/test result or measurement with a value and "
        "unit, such as Hemoglobin, WBC Count, Heart Rate, Blood Pressure, "
        "Temperature, SpO2, PR Interval, QRS Duration, or QT Interval. For "
        "vitals, label is the parameter name, value is the numeric result, and "
        "unit is its unit. Conditions are named diagnoses, findings, or clinical "
        "assessments, not raw numbers, such as Normal Sinus Rhythm or "
        "ZZZ-Example-Condition. For conditions, status should reflect whether "
        "the condition is normal, resolved, active, or managed when stated; use "
        '"Noted" when no status is specified. Allergies must contain explicitly '
        "stated allergies only. Medications must contain only named drugs, with "
        "dosing information when present. History must contain past procedures, "
        "surgeries, or significant past events, with dates when present. "
        "For example, given the excerpt 'Hemoglobin 13.5 13.0 - 17.0 g/dL', "
        'extract {"label": "Hemoglobin", "value": "13.5", "unit": "g/dL"} '
        "under vitals. Never infer or invent data. Respond with ONLY the JSON "
        "object, no other text, no markdown code fences, in exactly this shape: "
        '{"allergies": [string], "conditions": [{"name": string, '
        '"status": string}], "medications": [{"name": string, "dose": string, '
        '"frequency": string, "purpose": string}], "history": [{"title": string, '
        '"year": string, "detail": string}], "vitals": [{"label": string, '
        '"value": string, "unit": string}]}. If no information exists for a '
        "category, return an empty list for it — never invent information not "
        "present in the provided context. The example(s) above are ONLY to show "
        "you the correct JSON format. Do NOT include the example values "
        "themselves in your output under any circumstances. Only include an "
        "entry in any category if the exact information appears in the 'Report "
        "excerpts' section below. If you are not sure whether something was "
        "explicitly stated in the report excerpts, leave it out.\n\n"
        f"{RECENCY_INSTRUCTION}\n\n"
        f"Report excerpts:\n{_context_text(context_chunks)}"
    )

    response = ollama.chat(
        model=MODEL,
        messages=[{"role": "user", "content": prompt}],
    )
    content = _strip_markdown_fencing(_response_content(response))
    try:
        parsed = json.loads(content)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass

    retry_response = ollama.chat(
        model=MODEL,
        messages=[
            {
                "role": "user",
                "content": (
                    f"{prompt}\n\nYour last response was not valid JSON, "
                    "respond with ONLY valid JSON this time."
                ),
            }
        ],
    )
    retry_content = _strip_markdown_fencing(_response_content(retry_response))
    try:
        parsed = json.loads(retry_content)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass

    return _empty_structured_data()
